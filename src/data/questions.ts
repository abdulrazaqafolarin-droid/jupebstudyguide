export const getQuestionsBySubject = (subject: Subject): Question[] => {
  return questions.filter(q => q.subject === subject);
};

export const getQuestionsByYear = (year: number): Question[] => {
  return questions.filter(q => q.year === year);
};

export const getRandomQuestions = (count: number, subject?: Subject): Question[] => {
  const pool = subject ? getQuestionsBySubject(subject) : questions;
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
};

