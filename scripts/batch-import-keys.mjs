import { readFileSync, writeFileSync } from "fs";
import crypto from "crypto";

const KEY_ENCRYPTION_SECRET = process.env.KEY_ENCRYPTION_SECRET;
if (!KEY_ENCRYPTION_SECRET) {
  console.error("FATAL: Set KEY_ENCRYPTION_SECRET env var");
  process.exit(1);
}

const keysFile = process.argv[2] || "C:/Users/HP/Downloads/gemini api.txt";
const content = readFileSync(keysFile, "utf-8");

const keyRegex = /X-goog-api-key:\s*(\S+)/g;
const seen = new Set();
const keys = [];
let m;
while ((m = keyRegex.exec(content)) !== null) {
  let k = m[1];
  k = k.replace(/['"]$/, '');
  if (!seen.has(k)) { seen.add(k); keys.push(k); }
}

console.log(`Found ${keys.length} unique API keys\n`);

const PBKDF2_SALT = "ai-key-vault-salt-v1";

function sqlEscape(s) {
  return s.replace(/'/g, "''");
}

function encrypt(plaintext) {
  const saltBuf = Buffer.from(PBKDF2_SALT, "utf8");
  const key = crypto.pbkdf2Sync(KEY_ENCRYPTION_SECRET, saltBuf, 100000, 32, "sha256");
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv("aes-256-gcm", key, iv);
  const c1 = cipher.update(plaintext, "utf8");
  const c2 = cipher.final();
  const tag = cipher.getAuthTag();
  const combined = Buffer.concat([iv, c1, c2, tag]);
  return combined.toString("base64");
}

const inserts = [];
for (let i = 0; i < keys.length; i++) {
  const encrypted = encrypt(keys[i]);
  const preview = `••••••••••••${keys[i].slice(-4)}`;
  const label = `Key ${String(i + 1).padStart(2, "0")}`;
  const priority = i + 1;
  inserts.push(
    `('${sqlEscape(label)}', '${sqlEscape(encrypted)}', '${sqlEscape(preview)}', ${priority})`
  );
}

const sql = `-- Batch import ${keys.length} Gemini API keys
-- Generated by batch-import-keys.mjs

INSERT INTO public.ai_api_keys (label, api_key, key_preview, priority)
VALUES\n${inserts.join(",\n")};\n`;

writeFileSync("import-keys.sql", sql, "utf-8");
console.log("SQL written to import-keys.sql");
